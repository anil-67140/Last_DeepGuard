/**
 * Generate PDF report for a completed job
 */
const generateReport = async (req, res) => {
  try {
    const { jobId } = req.params;

    const job = await Job.findOne({ jobId, userId: req.userId });
    if (!job) return res.status(404).json({ error: 'Job not found' });
    if (job.status !== 'completed') {
      return res.status(400).json({ error: `Job status is ${job.status}, not completed` });
    }

    // Get top fraudulent transactions
    const topFrauds = await Transaction.find({ jobId, isFraud: true })
      .sort({ riskScore: -1 })
      .limit(100)
      .lean();

    const allFrauds = await Transaction.find({ jobId, isFraud: true })
      .select('fraudCategory')
      .lean();

    // Generate AI summary
    const aiSummary = await generateAISummary(job, topFrauds.slice(0, 10));

    // FR-11 — evidence integrity hash, computed before rendering
    const evidenceHash = computeEvidenceHash(job, topFrauds);

    // Build HTML
    const html = buildReportHTML(job, allFrauds, aiSummary, topFrauds, evidenceHash);

    // Generate PDF with Puppeteer
    const reportFileName = `deepguard_report_${jobId}_${Date.now()}.pdf`;
    const reportPath = path.join(REPORTS_DIR, reportFileName);

    const browser = await puppeteer.launch({
      headless: 'new',
      args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage']
    });

    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: 'networkidle0' });
    await page.pdf({
      path: reportPath,
      format: 'A4',
      printBackground: true,
      margin: { top: '0', right: '0', bottom: '0', left: '0' }
    });

    await browser.close();

    // Update job with report URL + evidence hash + generation timestamp (FR-11)
    const reportGeneratedAt = new Date();
    await Job.findOneAndUpdate({ jobId }, { reportUrl: reportFileName, reportHash: evidenceHash, reportGeneratedAt });

    // Stream PDF to client
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="DeepGuard_Forensic_Report_${jobId}.pdf"`);
    res.setHeader('X-Report-Evidence-SHA256', evidenceHash);
    const stream = fs.createReadStream(reportPath);
    stream.pipe(res);
    stream.on('end', () => fs.unlink(reportPath, () => {}));

  } catch (err) {
    console.error('Report generation error:', err);
    res.status(500).json({ error: err.message });
  }
};

/**
 * FR-11 (continued) — GET /api/reports/verify/:jobId
 * Lets anyone holding a copy of a report confirm its evidence hash hasn't
 * drifted from what DeepGuard originally recorded for that job.
 */
const verifyReport = async (req, res) => {
  try {
    const { jobId } = req.params;
    const job = await Job.findOne({ jobId }).lean();
    if (!job) return res.status(404).json({ error: 'Job not found' });
    if (!job.reportHash) {
      return res.status(404).json({ error: 'No report has been generated for this job yet' });
    }
    res.json({
      jobId,
      evidenceHash: job.reportHash,
      reportGeneratedAt: job.reportGeneratedAt,
      note: 'Compare this hash against the "Evidence Integrity Hash" printed in the footer of your PDF copy. A match confirms the underlying findings have not been altered since generation.'
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
};

module.exports = { generateReport, verifyReport };
